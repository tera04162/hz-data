def josa(word: str, a: str, b: str) -> str:
    """받침 있으면 a, 없으면 b (예: 이/가)."""
    w = word.rstrip(")")
    ch = w[-1]
    if "가" <= ch <= "힣":
        return a if (ord(ch) - 0xAC00) % 28 else b
    return a if ch in "013678LMNRlmnr" else b


def pc(v, d=1):
    return "–" if v is None else f"{'+' if v > 0 else ''}{v:.{d}f}%"


def kd(s):
    y, m, d = s.split("-")
    return f"{y}년 {int(m)}월 {int(d)}일"


def table(head, rows, note):
    th = "".join(f'<th style="padding:8px 6px;border-bottom:2px solid #ccc;text-align:{"left" if i == 0 else "right"};white-space:nowrap">{h}</th>' for i, h in enumerate(head))
    trs = "".join("<tr>" + "".join(
        f'<td style="padding:8px 6px;border-bottom:1px solid #e3e3e3;text-align:{"left" if i == 0 else "right"};white-space:nowrap">{c}</td>' for i, c in enumerate(r)) + "</tr>" for r in rows)
    return (f'<div style="overflow-x:auto"><table style="width:100%;border-collapse:collapse;font-size:15px"><thead><tr>{th}</tr></thead><tbody>{trs}</tbody></table></div>'
            f'<p style="text-align:right;font-size:12px;color:#888;margin:4px 0 18px">{note}</p>')


