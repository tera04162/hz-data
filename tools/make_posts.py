            out.append(f"<h2 {H2}>같은 날 이후 {T2}</h2><p>같은 신호를 {T2} 기준으로 보면, 3개월 뒤 오른 경우가 {a['win']:.0f}%(평소 {bb['win']:.0f}%), "
                       f"수익률 중앙값은 {pc(a['median'])}(평소 {pc(bb['median'])})였습니다. 가장 나빴던 경우는 {pc(a['min'])}, 가장 좋았던 경우는 {pc(a['max'])}입니다.</p>")

